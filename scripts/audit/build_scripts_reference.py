#!/usr/bin/env python3
"""
build_scripts_reference.py -- GENERATES docs/SCRIPTS_REFERENCE.md from the real files under scripts/ (written 2026-10-26). READ-ONLY on scripts; writes one file. Never edit the output by hand: rerun this script (it is safe to rerun any time).
Per script: last commit date, purpose (first paragraph of the module docstring, or the first comment of a .sh / .sql file), flags (EVERY --flag string found in the source, so manual sys.argv checks are caught as well as argparse), tables (.table("x") calls: W if a write verb follows in the same call chain, R otherwise; explicit INSERT / UPDATE / DELETE / CREATE TABLE statements are W), and a FROZEN marker for the eight forward-test files.
These are HEURISTICS read from the text, not from running the scripts: a table named only inside a dynamic string is missed, and a W is 'a write verb appears in the chain'. Where the heuristic is unsure the reference says nothing rather than guessing.
Run from the repository root:   python3 scripts/audit/build_scripts_reference.py
"""
import os, re, ast, sys, subprocess, datetime, collections

ROOT, OUT = "scripts", "docs/SCRIPTS_REFERENCE.md"
FROZEN = {"models/earnings_band_model.json", "models/earnings_role_band_model.json", "models/band_calibration.json", "scripts/card/earnings_roles.py", "scripts/card/earnings_role_band_test.py", "scripts/card/day_card.py", "scripts/card/earnings_surprise_test.py", "scripts/card/earnings_forward_test.py"}
FLAG = re.compile(r"(?<![\w-])--[a-z][a-z0-9-]{1,30}")
TABLE = re.compile(r"""\.table\(\s*["']([A-Za-z_][A-Za-z0-9_]*)["']\s*\)""")
WRITE = re.compile(r"\.(upsert|insert|update|delete)\(")
SQLW = re.compile(r"\b(?:INSERT\s+INTO|DELETE\s+FROM|CREATE\s+(?:OR\s+REPLACE\s+)?TABLE(?:\s+IF\s+NOT\s+EXISTS)?|ALTER\s+TABLE|DROP\s+TABLE(?:\s+IF\s+EXISTS)?)\s+(?:public\.)?([A-Za-z_][A-Za-z0-9_]*)|\bUPDATE\s+(?:public\.)?([A-Za-z_][A-Za-z0-9_]*)\s+SET\b")
RPC = re.compile(r"""\.rpc\(\s*["']([A-Za-z_][A-Za-z0-9_]*)["']""")
SKIP_TABLE_WORDS = {"set", "only", "if", "table", "values", "select", "from", "the", "a"}


def git(args):
    try:
        return subprocess.run(["git"] + args, capture_output=True, text=True, timeout=30).stdout.strip()
    except Exception:
        return ""


def last_commit(path):
    return git(["log", "-1", "--format=%ad", "--date=short", "--", path]) or "untracked"


def first_par(text, n=170):
    if not text:
        return ""
    par = [ln.strip() for ln in text.strip().split("\n\n")[0].split("\n") if ln.strip()]
    s = " ".join(par)
    return (s[:n] + "...") if len(s) > n else s


def analyse(path):
    src = open(path, encoding="utf-8", errors="replace").read()
    ext = os.path.splitext(path)[1]
    purpose = ""
    if ext == ".py":
        try:
            purpose = first_par(ast.get_docstring(ast.parse(src)) or "")
        except SyntaxError:
            purpose = "(does not parse)"
        if not purpose:
            m = re.search(r"^#\s*(.+)$", src, re.M)
            purpose = m.group(1).strip()[:170] if m and not m.group(1).startswith("!") else ""
    else:
        for ln in src.split("\n"):
            s = ln.strip().lstrip("#-/* ").strip()
            if s and not s.startswith("!") and not ln.startswith("#!"):
                purpose = s[:170]; break
    flags = sorted(set(FLAG.findall(src)))
    tables = collections.OrderedDict()
    for m in TABLE.finditer(src):
        chain = src[m.end():m.end() + 400]
        nxt = chain.find(".table(")
        chain = chain if nxt < 0 else chain[:nxt]
        kind = "W" if WRITE.search(chain) else "R"
        t = m.group(1)
        tables[t] = "W" if (tables.get(t) == "W" or kind == "W") else "R"
    for m in SQLW.finditer(src):
        t = (m.group(1) or m.group(2)).lower()
        if t not in SKIP_TABLE_WORDS:
            tables[t] = "W"
    for m in RPC.finditer(src):
        tables["rpc:" + m.group(1)] = "call"
    return purpose, flags, tables


def esc(s):
    return s.replace("|", "/").replace("\n", " ")


def main():
    files = []
    for dp, dn, fn in os.walk(ROOT):
        dn[:] = sorted(d for d in dn if not d.startswith(".") and d != "__pycache__")
        files += [os.path.join(dp, f) for f in sorted(fn) if os.path.splitext(f)[1] in (".py", ".sh", ".sql") and not f.startswith(".")]
    by_dir = collections.OrderedDict(); writers = collections.defaultdict(list); readers = collections.defaultdict(list)
    for p in files:
        purpose, flags, tables = analyse(p)
        by_dir.setdefault(os.path.dirname(p), []).append((p, last_commit(p), purpose, flags, tables))
        for t, k in tables.items():
            (writers if k == "W" else readers)[t].append(os.path.basename(p))
    commit = git(["rev-parse", "--short", "HEAD"]) or "unknown"
    out = ["# SCRIPTS REFERENCE", "", "_Generated by scripts/audit/build_scripts_reference.py on %s at commit %s. **Do not edit by hand**: rerun the script. %d files in %d folders._" % (datetime.date.today().isoformat(), commit, len(files), len(by_dir)), "",
           "How to read it: **flags** = every `--flag` string in the source (argparse and manual argument checks); **tables** = `.table(\"x\")` calls, `W` when a write verb follows in the same call chain, `R` otherwise, plus explicit INSERT / UPDATE / DELETE / CREATE statements (uppercase keywords only; always `W`), and `rpc:name` for database function calls. These are heuristics read from the text, not from running the scripts. `FROZEN` marks the forward-test files that the pre-commit hook protects. Procedures and the order to run things in: docs/OPERATIONS.md. History: CHANGELOG.md.", "", "## Folders", ""]
    for d, items in by_dir.items():
        out.append("- [%s](#%s) (%d)" % (d, re.sub(r"[^a-z0-9 -]", "", d.lower()).replace(" ", "-"), len(items)))
    for d, items in by_dir.items():
        out += ["", "## %s" % d, "", "| script | last commit | purpose | flags | tables |", "|---|---|---|---|---|"]
        for p, lc, purpose, flags, tables in items:
            tcell = ", ".join((t if k == "call" else "%s(%s)" % (t, k)) for t, k in tables.items())
            mark = " **FROZEN**" if p in FROZEN else ""
            out.append("| %s%s | %s | %s | %s | %s |" % (os.path.basename(p), mark, lc, esc(purpose), esc(" ".join(flags)), esc(tcell[:300])))
    out += ["", "## Who writes which table (heuristic)", "", "| table | written by | also read by |", "|---|---|---|"]
    for t in sorted(set(writers) | set(readers)):
        if writers.get(t):
            out.append("| %s | %s | %s |" % (t, esc(", ".join(sorted(set(writers[t])))[:300]), esc(", ".join(sorted(set(readers.get(t, [])))[:12]))))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write("\n".join(out) + "\n")
    nflags = sum(1 for items in by_dir.values() for it in items if it[3]); nt = sum(1 for items in by_dir.values() for it in items if it[4]); nnop = sum(1 for items in by_dir.values() for it in items if not it[2])
    print("wrote %s: %d files in %d folders; %d with flags, %d touching tables, %d without a purpose line" % (OUT, len(files), len(by_dir), nflags, nt, nnop))
    print("folders:", {d: len(i) for d, i in by_dir.items()})


if __name__ == "__main__":
    main()