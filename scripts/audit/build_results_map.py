#!/usr/bin/env python3
"""
build_results_map.py -- GENERATES docs/RESULTS_MAP.md: where every file in results/ came from (written 2026-10-26). READ-ONLY on the repository; writes one file; safe to rerun any time; never edit the output by hand.
For every file in results/: its kind, last commit date, size, first line, and the CHANGELOG entries that mention it (by path, file name, its folder, or its file-family prefix such as tag_review_v1_primary). It also lists (a) files in results/ that NO changelog entry mentions (undocumented), and (b) paths that a changelog entry cites under results/ that do not exist (dangling references).
Run from the repository root:   python3 scripts/audit/build_results_map.py
"""
import os, re, sys, subprocess, collections, datetime
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import changelog_tools as C

KINDS = [
    (r"^(PREREG_|FROZEN_|DESIGN_|TEMPLATE_)|^ANCHORS\.md$|^JANUARY_", "Registrations, rules and the runbook"),
    (r"^tag_review_v1_", "Government tag review sample (hand-read design)"),
    (r"^(cards/)", "Stock-day cards (JSON)"),
    (r"^(maps/)", "Market day maps (JSON)"),
    (r"^\d{4}-\d\d-\d\d/", "Run outputs (.out / .log), by date"),
    (r"^fomc_", "FOMC calendar and validation"),
    (r"^prediction_", "Prediction tally and log"),
    (r"^exhibit_reclass", "Exhibit re-classification test"),
    (r"(_sheet|_prescreened)\.csv$|^human_review|^random_audit|^bucket_\d|^pile\d", "Classifier review sheets and queues"),
    (r"^unrecorded_|^gap_sample|^archive_", "Unrecorded-event candidates, gap samples and archive"),
    (r"^eo_", "Executive-order watch item"),
    (r"^guidance_", "Guidance variance study"),
]


def kind_of(rel):
    for pat, name in KINDS:
        if re.search(pat, rel):
            return name
    return "Other"


def git_date(path):
    try:
        out = subprocess.run(["git", "log", "-1", "--format=%ad", "--date=short", "--", path], capture_output=True, text=True, timeout=20).stdout.strip()
        return out or "untracked"
    except Exception:
        return "?"


def first_line(path):
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            for line in f:
                s = line.strip()
                if s:
                    return s.lstrip("# ").replace("|", "/")[:90]
    except Exception:
        pass
    return ""


def main():
    ents = C.parse_changelog(open("CHANGELOG.md", encoding="utf-8").read())
    texts = {e["id"]: e["title"] + "\n" + "\n".join(C.body_of(e)) for e in ents}
    files = []
    for dp, dn, fn in os.walk("results"):
        dn[:] = sorted(d for d in dn if not d.startswith("."))
        files += [os.path.relpath(os.path.join(dp, f), "results").replace(os.sep, "/") for f in sorted(fn) if not f.startswith(".")]
    def family(base):
        stem = os.path.splitext(base)[0]
        stem = re.sub(r"(_part\d+|_sheet|_prescreened|_addendum_\d+|_\d{8}|_\d{4}-\d\d-\d\d)+$", "", stem)
        return stem if len(stem) >= 9 else None
    mentions = {p: [] for p in files}
    for eid, txt in texts.items():
        for p in files:
            base = os.path.basename(p); d = os.path.dirname(p); fam = family(base)
            if ("results/" + p) in txt or (len(base) >= 10 and base in txt) or (d and ("results/" + d + "/") in txt) or (fam and fam in txt):
                mentions[p].append(eid)
    cited = collections.defaultdict(set)
    for eid, txt in texts.items():
        for m in re.findall(r"results/[A-Za-z0-9_./-]+", txt):
            m = m.rstrip(".,;:)")
            if "*" in m or "<" in m or m.endswith("/") and False:
                continue
            cited[m].add(eid)
    dangling = {m: sorted(v) for m, v in cited.items() if not os.path.exists(m) and m != "results/" and "." in os.path.basename(m)}
    by_kind = collections.OrderedDict()
    for p in files:
        by_kind.setdefault(kind_of(p), []).append(p)
    order = [k for _, k in KINDS] + ["Other"]
    out = ["# RESULTS MAP", "", "_GENERATED by scripts/audit/build_results_map.py on %s. **Do not edit by hand**: rerun the script._" % datetime.date.today().isoformat(), "",
           "Where every file in results/ came from. 'Entries' are the CHANGELOG entries that mention the file by path, name, folder or family prefix; **UNDOCUMENTED** means no entry mentions it. Registrations (PREREG, FROZEN, DESIGN) hold the rule written BEFORE a test; the verdict is in the entries listed beside it.", "",
           "## Summary", "", "| kind | files | MB | undocumented |", "|---|---|---|---|"]
    for k in order:
        ps = by_kind.get(k, [])
        if ps:
            out.append("| %s | %d | %.2f | %d |" % (k, len(ps), sum(os.path.getsize("results/" + p) for p in ps) / 1e6, sum(1 for p in ps if not mentions[p])))
    out.append("| **all** | **%d** | **%.2f** | **%d** |" % (len(files), sum(os.path.getsize("results/" + p) for p in files) / 1e6, sum(1 for p in files if not mentions[p])))
    for k in order:
        ps = by_kind.get(k, [])
        if not ps:
            continue
        out += ["", "## %s" % k, "", "| file | last commit | KB | first line | entries |", "|---|---|---|---|---|"]
        for p in ps:
            ids = mentions[p]
            e = ", ".join(ids[:4]) + (" (+%d)" % (len(ids) - 4) if len(ids) > 4 else "") if ids else "**UNDOCUMENTED**"
            out.append("| %s | %s | %.0f | %s | %s |" % (p, git_date("results/" + p), os.path.getsize("results/" + p) / 1024.0, first_line("results/" + p), e))
    out += ["", "## Cited in the changelog but missing from results/", ""]
    if dangling:
        out += ["| path | cited by |", "|---|---|"] + ["| %s | %s |" % (m, ", ".join(v[:4])) for m, v in sorted(dangling.items())]
    else:
        out.append("(none)")
    os.makedirs("docs", exist_ok=True)
    open("docs/RESULTS_MAP.md", "w", encoding="utf-8").write("\n".join(out) + "\n")
    und = [p for p in files if not mentions[p]]
    print("wrote docs/RESULTS_MAP.md: %d files in %d kinds; %d undocumented; %d dangling references; changelog entries read: %d" % (len(files), len(by_kind), len(und), len(dangling), len(ents)))
    print("by kind:", {k: len(v) for k, v in by_kind.items()})
    print("undocumented (first 25):", und[:25])
    print("dangling (first 12):", list(sorted(dangling))[:12])


if __name__ == "__main__":
    main()